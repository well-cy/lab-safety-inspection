def load_index():
    out = {}
    for line in INDEX.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) == 2:
            out[int(parts[0])] = Path(parts[1]).stem
    return out


def xyxy2cxcywh(b):
    x0, y0, x1, y1 = b
    return ((x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0)


def cxcywh2xyxy(c):
    cx, cy, w, h = c
    return (cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2)


def cdist(a, b):
    return ((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2) ** 0.5


def match_box(rows, used, cls, target_xyxy):
    tc = xyxy2cxcywh(target_xyxy)
    best, best_d = None, 1e9
    for i, (c, box) in enumerate(rows):
        if used[i] or (cls is not None and c != cls):
            continue
        d = cdist((box[0], box[1]), (tc[0], tc[1]))
        if d < best_d:
            best, best_d = i, d
    return best if (best is not None and best_d < TOL) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    idx = load_index()
    stats = {"DEL": 0, "SET": 0, "SETCLS": 0, "ADD": 0}
    problems = []
    totals = {c: 0 for c in CLS}

    for num in sorted(FIXES):
        stem = idx.get(num)
        if stem is None:
            problems.append(f"#{num}: index 无此编号")
            continue
        lbl = LBL_DIR / f"{stem}.txt"
        if not lbl.exists():
            problems.append(f"#{num}: 缺标签 {lbl.name}")
            continue

        rows = []
        for ln in lbl.read_text(encoding="utf-8").splitlines():
            ln = ln.strip()
            if not ln:
                continue
            p = ln.split()
            rows.append([int(p[0]), tuple(float(v) for v in p[1:5])])
        n0 = len(rows)
        used = [False] * len(rows)      # 已被任何动作匹配过(防重复匹配)
        deleted = [False] * len(rows)   # 仅 DEL 命中的框(final 时剔除)
        adds, log = [], []

        for op in FIXES[num]:
            kind = op[0]
            if kind == "DEL":
                _, cls, old = op
                i = match_box(rows, used, cls, old)
                if i is None:
                    problems.append(f"#{num}: DEL 未匹配 cls={cls} {old}")
                    continue
                c, b = rows[i]
                log.append(f"  DEL  [{i}] {CLS[c]} cxcywh=({b[0]:.3f},{b[1]:.3f},{b[2]:.3f},{b[3]:.3f})")
                used[i] = True
                deleted[i] = True
                stats["DEL"] += 1
            elif kind == "SET":
                _, cls, old, (nc, nb) = op
                i = match_box(rows, used, cls, old)
                if i is None:
                    problems.append(f"#{num}: SET 未匹配 cls={cls} {old}")
                    continue
                c, b = rows[i]
                log.append(f"  SET  [{i}] {CLS[c]} ({b[0]:.2f},{b[1]:.2f},{b[2]:.2f},{b[3]:.2f})"
                           f" -> {CLS[nc]} {tuple(round(v,2) for v in xyxy2cxcywh(nb))}")
                rows[i] = [nc, xyxy2cxcywh(nb)]
                used[i] = True
                stats["SET"] += 1
            elif kind == "SETCLS":
                _, cls, old, nc, nb = op
                i = match_box(rows, used, cls, old)
                if i is None:
                    problems.append(f"#{num}: SETCLS 未匹配 cls={cls} {old}")
                    continue
                c, b = rows[i]
                log.append(f"  SETCLS[{i}] {CLS[c]} -> {CLS[nc]} {tuple(round(v,2) for v in xyxy2cxcywh(nb))}")
                rows[i] = [nc, xyxy2cxcywh(nb)]
                used[i] = True
                stats["SETCLS"] += 1
            elif kind == "ADD":
                _, cls, nb = op
                adds.append((cls, xyxy2cxcywh(nb)))
                log.append(f"  ADD  {CLS[cls]} {tuple(round(v,2) for v in xyxy2cxcywh(nb))}")
                stats["ADD"] += 1

        final = [tuple(r) for i, r in enumerate(rows) if not deleted[i]] + adds
        for c, b in final:
            assert c in CLS, f"#{num} 坏类别 {c}"
            assert all(-0.001 <= v <= 1.001 for v in b), f"#{num} 越界 {b}"
            assert b[2] > 0 and b[3] > 0, f"#{num} 零尺寸 {b}"
            totals[c] += 1

        print(f"#{num} {stem[:36]}  框 {n0} -> {len(final)}")
        for line in log:
            print(line)

        if args.apply:
            BACKUP.mkdir(parents=True, exist_ok=True)
            bak = BACKUP / f"{stem}.txt"
            if not bak.exists():
                shutil.copyfile(lbl, bak)
            lbl.write_text("".join(
                f"{c} {b[0]:.6f} {b[1]:.6f} {b[2]:.6f} {b[3]:.6f}\n" for c, b in final),
                encoding="utf-8")

    print(f"\n统计: {stats}")
